// ============================================================
// Complex Hack Assembler Test
//
// Input:
//   R0 = n
//
// Output:
//   R1 = 1 + 2 + ... + n
//
// Side effect:
//   Writes R1 repeatedly to the first 16 words of SCREEN.
//
// ============================================================


// ------------------------------------------------------------
// N = R0
// ------------------------------------------------------------

@R0
D=M

@N
M=D


// ------------------------------------------------------------
// result = 0
// ------------------------------------------------------------

@0
D=A

@R1
M=D


// ------------------------------------------------------------
// i = 1
// ------------------------------------------------------------

@1
D=A

@i
M=D


// ------------------------------------------------------------
// Sum loop
// ------------------------------------------------------------

(SUM_LOOP)

    // if i > N, go to SUM_DONE

    @i
    D=M

    @N
    D=D-M

    @SUM_DONE
    D;JGT


    // result = result + i

    @i
    D=M

    @R1
    M=D+M


    // i++

    @i
    M=M+1


    @SUM_LOOP
    0;JMP


// ------------------------------------------------------------
// Write result to the first 16 screen words.
// ------------------------------------------------------------

(SUM_DONE)

    // screenPtr = SCREEN

    @SCREEN
    D=A

    @screenPtr
    M=D


    // screenCounter = 16

    @16
    D=A

    @screenCounter
    M=D


// ------------------------------------------------------------
// Screen loop
// ------------------------------------------------------------

(SCREEN_LOOP)

    // Stop when screenCounter == 0

    @screenCounter
    D=M

    @SCREEN_DONE
    D;JEQ


    // RAM[screenPtr] = result

    @R1
    D=M

    @screenPtr
    A=M
    M=D


    // screenPtr++

    @screenPtr
    M=M+1


    // screenCounter--

    @screenCounter
    M=M-1


    @SCREEN_LOOP
    0;JMP


// ------------------------------------------------------------
// Done writing to screen
// ------------------------------------------------------------

(SCREEN_DONE)


// ------------------------------------------------------------
// temp = R1 * 2
//
// Standard Hack has no multiplication instruction,
// so this is implemented as:
//
// temp = R1
// temp = temp + temp
// ------------------------------------------------------------

@R1
D=M

@temp
M=D

@temp
D=M

@temp
M=D+M


// ------------------------------------------------------------
// Conditional branch using the calculated value.
// ------------------------------------------------------------

@temp
D=M

@POSITIVE
D;JGT

@NEGATIVE
0;JMP


// ------------------------------------------------------------
// Positive result
// ------------------------------------------------------------

(POSITIVE)

@1
D=A

@R2
M=D

@END
0;JMP


// ------------------------------------------------------------
// Negative result
// ------------------------------------------------------------

(NEGATIVE)

@1
D=A

@R2
M=-D


// ------------------------------------------------------------
// Infinite end loop
// ------------------------------------------------------------

(END)

@END
0;JMP